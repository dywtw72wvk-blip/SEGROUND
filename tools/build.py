#!/usr/bin/env python3
"""Fleet System build tool.

  python3 tools/build.py          assemble paste-ready scripts into dist/
  python3 tools/build.py --check  also compile each script against the API stubs
                                  (needs `mcs` from Mono; C# 6, same as the game)

Each src file is a "PB body" fragment (members of the Program class), exactly
what you paste into the in-game editor. The build simply concatenates the
fragments for each programmable block.
"""
import pathlib
import shutil
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
DIST = ROOT / "dist"
STUBS = ROOT / "tools" / "stubs" / "SEStubs.cs"
VERSION = "0.3.0-phase3"
PB_CHAR_LIMIT = 100_000

SHARED = ["Shared/Proto.cs", "Shared/Util.cs", "Shared/Cfg.cs", "Shared/Net.cs", "Shared/Frame.cs"]
SCRIPTS = {
    "HubCore": ["HubCore/Program.cs", "HubCore/Drone.cs", "HubCore/Docks.cs", "HubCore/Formation.cs"] + SHARED,
    "HubUI": ["HubUI/Program.cs", "HubUI/Draw.cs"] + SHARED,
    "Drone": ["Drone/Program.cs", "Drone/Flight.cs"] + SHARED + ["Shared/Telemetry.cs"],
    "Factory": ["Factory/Program.cs"] + SHARED,
}

USINGS = """using System;
using System.Collections.Generic;
using System.Text;
using VRage;
using VRage.Game;
using VRageMath;
using VRage.Game.ModAPI.Ingame;
using VRage.Game.ModAPI.Ingame.Utilities;
using VRage.Game.GUI.TextPanel;
using Sandbox.ModAPI.Ingame;
using SpaceEngineers.Game.ModAPI.Ingame;
"""


def assemble(name, files):
    header = (f"// FLEET SYSTEM {VERSION} — {name}\n"
              f"// Generated by tools/build.py from src/. Paste this whole file into the programmable block.\n\n")
    body = "\n".join((SRC / f).read_text(encoding="utf-8").rstrip() + "\n" for f in files)
    return header + body


def check(name, code):
    with tempfile.TemporaryDirectory() as tmp:
        wrapper = pathlib.Path(tmp) / f"{name}.cs"
        wrapper.write_text(USINGS + f"\nnamespace FleetCheck_{name}\n{{\npublic partial class Program : MyGridProgram\n{{\n"
                           + code + "\n}\n}\n", encoding="utf-8")
        cmd = ["mcs", "-langversion:6", "-target:library", "-nologo", "-warn:3",
               "-nowarn:0169,0414,0649", f"-out:{tmp}/{name}.dll", str(STUBS), str(wrapper)]
        r = subprocess.run(cmd, capture_output=True, text=True)
        out = (r.stdout + r.stderr).strip()
        return r.returncode == 0, out


def main():
    do_check = "--check" in sys.argv
    if do_check and not shutil.which("mcs"):
        sys.exit("mcs not found (apt-get install mono-mcs)")
    DIST.mkdir(exist_ok=True)
    ok_all = True
    for name, files in SCRIPTS.items():
        code = assemble(name, files)
        (DIST / f"{name}.cs").write_text(code, encoding="utf-8")
        size = len(code)
        status = f"{name:8s} {size:6d} chars ({100 * size / PB_CHAR_LIMIT:4.1f}% of PB limit)"
        if size > PB_CHAR_LIMIT:
            status += "  OVER LIMIT"
            ok_all = False
        if do_check:
            ok, out = check(name, code)
            status += "  compile: " + ("OK" if ok else "FAILED")
            ok_all &= ok
            print(status)
            if out:
                print("  " + out.replace("\n", "\n  "))
        else:
            print(status)
    # ship blueprints embed the freshly built scripts
    r = subprocess.run([sys.executable, str(ROOT / "tools" / "shipgen.py")], capture_output=True, text=True)
    print("Ship blueprints  " + ("OK (see blueprints/STATS.txt)" if r.returncode == 0 else "FAILED\n  " + (r.stdout + r.stderr).strip()))
    ok_all &= r.returncode == 0
    if do_check:
        with tempfile.TemporaryDirectory() as tmp:
            r = subprocess.run(["mcs", "-langversion:5", "-nologo", "-r:System.Xml.dll", f"-out:{tmp}/FleetPatch.exe",
                                str(ROOT / "tools" / "FleetPatch.cs")], capture_output=True, text=True)
            print("FleetPatch (installer, C# 5)  compile: " + ("OK" if r.returncode == 0 else "FAILED"))
            if r.returncode != 0:
                print("  " + (r.stdout + r.stderr).strip().replace("\n", "\n  "))
                ok_all = False
    sys.exit(0 if ok_all else 1)


if __name__ == "__main__":
    main()
